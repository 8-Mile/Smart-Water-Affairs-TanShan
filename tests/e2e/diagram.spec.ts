import { test, expect, type Page } from '@playwright/test';

async function createSpray(page: Page, code: string, zone: 'A' | 'B') {
  await page.goto('/operations/assets');
  await page.getByRole('banner').getByRole('button', { name: '问 AI', exact: true }).click();
  await page.locator('.n-drawer textarea').first().fill(`在射雾器除尘系统新增${code.slice(-1)}号射雾器，编号${code}，位于${zone}区，配置运行状态、压力和喷射流量测点，并添加到工艺图。`);
  await page.getByRole('button', { name: '解析指令', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'AI 新增设备 · 五步向导', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.locator('.canvas.interactive').click({ position: { x: 200, y: zone === 'B' ? 270 : 70 } });
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.getByRole('button', { name: '确认创建', exact: true }).click();
  await expect(page.getByRole('heading', { name: '创建成功' })).toBeVisible();
}

test('动态组态发布第五和第六台射雾器，刷新与首页热点保留', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    if (!sessionStorage.getItem('__diagram_test_started')) {
      localStorage.clear(); localStorage.setItem('tanggang-demo-role', 'admin');
      sessionStorage.setItem('__diagram_test_started', '1');
    }
  });
  await createSpray(page, 'SP-005', 'B');
  await page.screenshot({ path: testInfo.outputPath('sp005-created.png'), fullPage: true });
  await createSpray(page, 'SP-006', 'B');
  await page.goto('/process/spray');
  await page.getByRole('button', { name: '编辑组态' }).click();
  await expect(page.locator('[data-node-id="node-asset-sp005"]')).toBeVisible();
  await expect(page.locator('[data-node-id="node-asset-sp006"]')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('scada-editor.png'), fullPage: true });
  await page.getByRole('button', { name: '校验并发布' }).click();
  await expect(page.locator('[data-node-id^="node-asset-sp00"]')).toHaveCount(6);
  await page.getByRole('button', { name: '编辑组态' }).click();
  await expect(page.locator('rect[fill="url(#spray-edit-grid)"]')).toBeVisible();
  const tankImage = page.locator('[data-node-id="spray-tank"] image');
  const tankBox = await tankImage.boundingBox();
  if (!tankBox) throw new Error('蓄水池图元不可见');
  const tankX = tankBox.x + tankBox.width / 2;
  const tankY = tankBox.y + tankBox.height / 2;
  await page.mouse.move(tankX, tankY);
  await page.mouse.down();
  await page.mouse.move(tankX + 15, tankY, { steps: 3 });
  await expect(page.locator('.alignment-guides')).toBeVisible();
  await page.mouse.up();
  const tankTransform = await page.locator('[data-node-id="spray-tank"]').getAttribute('transform');
  expect(tankTransform).not.toContain('translate(36 128) scale');
  const node = page.locator('[data-node-id="node-asset-sp005"]');
  const before = Number(await node.locator('image').getAttribute('x'));
  const box = await node.boundingBox();
  if (!box) throw new Error('SP-005 图元不可见');
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 10, box.y + box.height / 2, { steps: 5 });
  await page.mouse.up();
  const moved = Number(await node.locator('image').getAttribute('x'));
  expect(moved).toBeGreaterThan(before);
  await page.getByRole('button', { name: '保存草稿' }).click();
  await page.getByRole('button', { name: '校验并发布' }).click();
  await page.reload();
  await expect(page.locator('[data-node-id^="node-asset-sp00"]')).toHaveCount(6);
  await expect(page.locator('[data-node-id="spray-tank"]')).toHaveAttribute('transform', tankTransform!);
  await expect(page.locator('rect[fill="url(#spray-edit-grid)"]')).toHaveCount(0);
  await expect(page.locator('[data-node-id="node-asset-sp005"] image')).toHaveAttribute('x', String(moved));
  await page.getByRole('button', { name: '编辑组态' }).click();
  await page.locator('[data-node-id="node-asset-sp005"]').click({ force: true });
  await page.locator('.diagram-properties input[type="number"]').first().fill(String(moved + 100));
  await page.locator('.diagram-properties input[type="number"]').first().press('Tab');
  await page.getByRole('button', { name: '取消修改' }).click();
  await expect(page.locator('[data-node-id="node-asset-sp005"] image')).toHaveAttribute('x', String(moved));
  await page.screenshot({ path: testInfo.outputPath('six-spray-units.png'), fullPage: true });
  const workspace = page.locator('.diagram-workspace');
  const scadaSize = await workspace.boundingBox();
  await page.getByRole('button', { name: '工艺图', exact: true }).click();
  const sceneSize = await workspace.boundingBox();
  expect(sceneSize?.width).toBe(scadaSize?.width);
  expect(sceneSize?.height).toBe(scadaSize?.height);
  await expect(page.getByAltText('射雾器工艺场景底图，包含 A 区和 B 区')).toBeVisible();
  await expect(page.getByRole('group', { name: '工艺视图' }).getByRole('button', { name: '工艺图', exact: true })).toHaveAttribute('aria-pressed', 'true');
  const sceneDevices = page.locator('.scene-devices button');
  await expect(sceneDevices).toHaveCount(6);
  await expect(sceneDevices.filter({ hasText: 'SP-005' })).toContainText('末端压力');
  const addedDevice = page.getByRole('button', { name: '查看设备 SP-005', exact: true });
  await expect(addedDevice.locator('img')).toBeVisible();
  await expect.poll(() => addedDevice.locator('img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
  await addedDevice.click();
  const deviceInfo = page.getByRole('dialog');
  await expect(deviceInfo).toContainText('设备基础信息');
  await expect(deviceInfo).toContainText('SP-005');
  await expect(deviceInfo).toContainText('末端压力');
  await page.keyboard.press('Escape');
  await expect(deviceInfo).toBeHidden();
  await page.getByRole('button', { name: '组态图', exact: true }).click();
  await expect(page.locator('[data-node-id^="node-asset-sp00"]')).toHaveCount(6);
  await page.goto('/');
  await page.getByRole('button', { name: '管理设备热点' }).click();
  await page.getByLabel('选择热点设备').selectOption('asset-sp005');
  await page.locator('.map').click({ position: { x: 600, y: 180 } });
  await expect(page.getByRole('button', { name: 'SP-005', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'SP-005', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('overview-hotspot.png'), fullPage: true });
});
